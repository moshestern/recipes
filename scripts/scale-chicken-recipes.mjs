import fs from 'node:fs';

const path = 'data/recipes.json';
const data = JSON.parse(fs.readFileSync(path, 'utf8'));
const recipe = id => {
  const r = data.recipes.find(x => x.id === id);
  if (!r) throw new Error(`Missing recipe ${id}`);
  return r;
};
const item = (r, id) => {
  for (const group of r.ingredient_groups) {
    const found = group.items.find(x => x.id === id);
    if (found) return found;
  }
  throw new Error(`Missing ingredient ${id} in ${r.id}`);
};
const step = (r, id) => {
  const found = r.steps.find(x => x.id === id);
  if (!found) throw new Error(`Missing step ${id} in ${r.id}`);
  return found;
};
const setItem = (r, id, quantity, display, unit) => {
  const x = item(r, id);
  x.quantity = quantity;
  x.display = display;
  if (unit) x.unit = unit;
};

